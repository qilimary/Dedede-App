def verify():
    titles = [rule[0] for rule in RULES] + [rule[0] for rule in EXTENSION_ASSERTIONS]
    if len(titles) != 44 or len(set(titles)) != 44 or set(titles) != set(NOTE_LABELS):
        raise AssertionError("Annotation category table must match all 44 grammar rules")
    if any(x not in {"", "搭配不当", "句式杂糅", "语义重复", "语序不当"} for x in NOTE_LABELS.values()):
        raise AssertionError("Unknown annotation category")
    total = 0

    # Addition safety-regression checks: positives AND near-miss legal Chinese examples.
    for title, pattern, repl_a, repl_c, must_hit, must_ignore in EXTENSION_ASSERTIONS:
        regex = re.compile(pattern)
        if regex.groups != 3:
            raise AssertionError(title + ": invalid capture groups")
        for sentence in must_hit:
            if regex.search(sentence) is None:
                raise AssertionError(title + " missed: " + sentence)
        for sentence in must_ignore:
            if regex.search(sentence) is not None:
                raise AssertionError(title + " false-positive: " + sentence)
    for title, regex, change1, change3, positives, negatives in RULES:
        compiled = re.compile(regex)
        if compiled.groups != 3:
            raise AssertionError(f"{title} has {compiled.groups} capture groups, expected 3")
        for sample in positives:
            if not compiled.search(sample):
                raise AssertionError(f"{title}: missed {sample!r}")
            total += 1
        for sample in negatives:
            if compiled.search(sample):
                raise AssertionError(f"{title}: false positive {sample!r}")
            total += 1
    for rx, sample, expected in [
        (HIGH_BOUND, "超过100元以上。", True),
        (HIGH_BOUND, "高于一百人以上", True),
        (HIGH_BOUND, "超过标准。100元以上", False),
        (HIGH_BOUND, "不超过100元以上。", False),
        (LOW_BOUND, "低于50元以下。", True),
        (LOW_BOUND, "少于三十人以下。", True),
        (LOW_BOUND, "不低于50元以下。", False),
    ]:
        if (re.search(rx, sample) is not None) != expected:
            raise AssertionError(f"Bounds false result: {sample}")
        total += 1
    if re.search(GUARD_REGEX, "期待地搓手手") is None:
        raise AssertionError("The expected target character was not protected")
    for example in ["期待的搓手手", "期待地搓手"]:
        if re.search(GUARD_REGEX, example):
            raise AssertionError(f"Accidental protection: {example}")
    return total + 3 + sum(len(rule[4]) + len(rule[5]) for rule in EXTENSION_ASSERTIONS)


def add_rule_line(regex, first, third, description):
    # Match the original Android convention: no third field means no explanation.
    choices = ("null" if first is None else jstr(first)) + ", " + ("null" if third is None else jstr(third))
    if description:
        choices += ", " + jstr(description)
    return "            addRule(" + jstr(regex) + ", new String[][]{{" + choices + "}});"


